export function sceneSupportsExperience(
  sceneId: CreativeSceneId,
  experienceMode: 'site' | 'app',
): boolean {
  return experienceMode === 'site' || APP_IDS.has(sceneId);
}

export function serializeCreativeSceneSignature(
  signature: CreativeSceneStructuralSignature,
): string {
  return [
    `sectionOrder=${signature.sectionOrder.join('>')}`,
    `compositionTopology=${signature.compositionTopology}`,
    `semanticRegions=${signature.semanticRegions.join('>')}`,
    `widgets=${signature.widgets.join('>')}`,
    `motions=${signature.motions.join('>')}`,
    `mediaTreatment=${signature.mediaTreatment}`,
    `interaction=${signature.interaction}`,
    `runtimeEngine=${signature.runtimeEngine}`,
    `costTier=${signature.costTier}`,
    `authoringTier=${signature.authoringTier}`,
  ].join('|');
}

export const CREATIVE_SCENE_STRUCTURAL_SIGNATURES = Object.fromEntries(
  CREATIVE_SCENE_IDS.map((id) => [
    id,
    serializeCreativeSceneSignature(CREATIVE_SCENE_CATALOG[id].signature),
  ]),
) as Readonly<Record<CreativeSceneId, string>>;

if (Object.keys(CREATIVE_SCENE_CATALOG).length !== CREATIVE_SCENE_IDS.length) {
  throw new Error('Creative scene catalog must have a bijection with the frozen IDs.');
}

if (new Set(Object.values(CREATIVE_SCENE_STRUCTURAL_SIGNATURES)).size !== CREATIVE_SCENE_IDS.length) {
  throw new Error('Creative scene structural signatures must be unique.');
}
