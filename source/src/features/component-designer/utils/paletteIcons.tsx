export type PaletteIconName = keyof typeof ICON_MAP;

export const hasPaletteIcon = (iconName: string): iconName is PaletteIconName =>
  Object.prototype.hasOwnProperty.call(ICON_MAP, iconName);

export const resolvePaletteIconComponent = (iconName: string) =>
  ICON_MAP[iconName as PaletteIconName] ?? LayoutTemplate;

export const getPaletteIcon = (iconName: DesignerPaletteItem['icon']): React.ReactNode => {
  const IconComponent = resolvePaletteIconComponent(iconName);
  return <IconComponent className="h-5 w-5" data-palette-icon={iconName} />;
};
