import { useCallback, useEffect, useMemo, useState } from 'react';
import { useRolesListQuery } from '../../../shared/api/queries/roles';
import { useServerFunctionActions } from './useServerFunctionActions';
import { useServerFunctionCatalog } from './useServerFunctionCatalog';
import { useServerFunctionEditor } from './useServerFunctionEditor';
import { useServerFunctionLogs } from './useServerFunctionLogs';
import { useServerFunctionRunner } from './useServerFunctionRunner';
import { useServerFunctionSettings } from './useServerFunctionSettings';
import { useServerFunctionsOverlayDeepLink } from './useServerFunctionsOverlayDeepLink';

export function useServerFunctionsPage() {
  const { logs, addLog } = useServerFunctionLogs();
  const [aiOpen, setAiOpen] = useState(false);
  const [isUnusedFunctionsDialogOpen, setIsUnusedFunctionsDialogOpen] = useState(false);
  const [toast, setToast] = useState<{ type: 'success' | 'error'; text: string } | null>(null);

  const showToast = useCallback((type: 'success' | 'error', text: string) => {
    setToast({ type, text });
  }, []);

  useEffect(() => {
    if (!toast) {
      return;
    }
    const timer = window.setTimeout(() => setToast(null), 4000);
    return () => window.clearTimeout(timer);
  }, [toast]);

  const catalog = useServerFunctionCatalog({ addLog });
  const settings = useServerFunctionSettings({ catalog, addLog });
  const editor = useServerFunctionEditor({
    catalog,
    addLog,
    showToast,
    globalDefaultVMMode: settings.globalDefaultVMMode,
    globalDefaultRAM: settings.globalDefaultRAM,
    globalDefaultTimeout: settings.globalDefaultTimeout,
  });
  const runner = useServerFunctionRunner({ editor, settings, addLog });
  const actions = useServerFunctionActions({ catalog, editor, settings, addLog, showToast });
  const rolesQuery = useRolesListQuery();
  const roleOptions = useMemo(
    () => (rolesQuery.data ?? []).map((role) => role.name).sort((left, right) => left.localeCompare(right)),
    [rolesQuery.data],
  );

  useServerFunctionsOverlayDeepLink({
    deleteOpen: Boolean(actions.idToDelete),
    renameOpen: actions.isRenameOpen,
    duplicateOpen: actions.isDuplicateOpen,
    createOpen: actions.isCreateOpen,
    settingsOpen: actions.isSettingsOpen,
    accessOpen: actions.isAccessOpen,
    hooksOpen: actions.isHooksOpen,
    unusedOpen: isUnusedFunctionsDialogOpen,
    bulkOpen: settings.isBulkOpen,
    aiOpen,
    openCreateDialog: actions.openCreateDialog,
    setIsSettingsOpen: actions.setIsSettingsOpen,
    setIsAccessOpen: actions.setIsAccessOpen,
    setIsHooksOpen: actions.setIsHooksOpen,
    setUnusedOpen: setIsUnusedFunctionsDialogOpen,
    setIsBulkOpen: settings.setIsBulkOpen,
    setAiOpen,
  });

  return {
    functions: catalog.functions,
    activeId: catalog.activeId,
    setActiveId: catalog.setActiveId,
    loadFunctionFromList: catalog.loadFunctionFromList,
    isNewDraftRoute: catalog.isNewDraftRoute,
    editSlugFromUrl: catalog.editSlugFromUrl,
    globalDefaultVMMode: settings.globalDefaultVMMode,
    setGlobalDefaultVMMode: settings.setGlobalDefaultVMMode,
    globalDefaultRAM: settings.globalDefaultRAM,
    setGlobalDefaultRAM: settings.setGlobalDefaultRAM,
    globalDefaultTimeout: settings.globalDefaultTimeout,
    setGlobalDefaultTimeout: settings.setGlobalDefaultTimeout,
    testVMMode: settings.testVMMode,
    setTestVMMode: settings.setTestVMMode,
    testRAM: settings.testRAM,
    setTestRAM: settings.setTestRAM,
    testTimeout: settings.testTimeout,
    setTestTimeout: settings.setTestTimeout,
    isBulkOpen: settings.isBulkOpen,
    setIsBulkOpen: settings.setIsBulkOpen,
    bulkVMMode: settings.bulkVMMode,
    setBulkVMMode: settings.setBulkVMMode,
    bulkRAM: settings.bulkRAM,
    setBulkRAM: settings.setBulkRAM,
    bulkTimeout: settings.bulkTimeout,
    setBulkTimeout: settings.setBulkTimeout,
    draftFn: editor.draftFn,
    setDraftFn: editor.setDraftFn,
    draftCodeIsAutoGeneratedRef: editor.draftCodeIsAutoGeneratedRef,
    getDraftPath: editor.getDraftPath,
    searchQuery: catalog.searchQuery,
    setSearchQuery: catalog.setSearchQuery,
    methodFilter: catalog.methodFilter,
    setMethodFilter: catalog.setMethodFilter,
    builtInFilter: catalog.builtInFilter,
    setBuiltInFilter: catalog.setBuiltInFilter,
    totalFunctionCount: catalog.functions.length,
    filteredFunctionCount: catalog.filteredFunctions.length,
    containerRef: editor.containerRef,
    column3Ref: editor.column3Ref,
    editorRef: editor.editorRef,
    injectMenuRef: editor.injectMenuRef,
    isInjectMenuOpen: editor.isInjectMenuOpen,
    setIsInjectMenuOpen: editor.setIsInjectMenuOpen,
    sidebarWidth: editor.sidebarWidth,
    payloadWidth: editor.payloadWidth,
    payloadHeight: editor.payloadHeight,
    isResizingSidebar: editor.isResizingSidebar,
    isResizingPayload: editor.isResizingPayload,
    isResizingPayloadHeight: editor.isResizingPayloadHeight,
    isLargeScreen: editor.isLargeScreen,
    toggleSidebar: editor.toggleSidebar,
    togglePayload: editor.togglePayload,
    payloadCollapsed: editor.payloadCollapsed,
    sidebarSplitHandleProps: editor.sidebarSplitHandleProps,
    payloadSplitHandleProps: editor.payloadSplitHandleProps,
    payloadHeightSplitHandleProps: editor.payloadHeightSplitHandleProps,
    isCreateOpen: actions.isCreateOpen,
    setIsCreateOpen: actions.setIsCreateOpen,
    isSettingsOpen: actions.isSettingsOpen,
    setIsSettingsOpen: actions.setIsSettingsOpen,
    settingsTarget: actions.settingsTarget,
    openSettingsDialog: actions.openSettingsDialog,
    closeSettingsDialog: actions.closeSettingsDialog,
    updateSettingsTarget: actions.updateSettingsTarget,
    saveSettingsFromList: actions.saveSettingsFromList,
    isSavingSettings: actions.isSavingSettings,
    isAccessOpen: actions.isAccessOpen,
    setIsAccessOpen: actions.setIsAccessOpen,
    accessTarget: actions.accessTarget,
    openAccessDialog: actions.openAccessDialog,
    closeAccessDialog: actions.closeAccessDialog,
    updateAccessTargetControl: actions.updateAccessTargetControl,
    saveAccessFromList: actions.saveAccessFromList,
    isSavingAccess: actions.isSavingAccess,
    isHooksOpen: actions.isHooksOpen,
    setIsHooksOpen: actions.setIsHooksOpen,
    newFuncName: actions.newFuncName,
    setNewFuncName: actions.setNewFuncName,
    newFuncTags: actions.newFuncTags,
    setNewFuncTags: actions.setNewFuncTags,
    newFuncMethod: actions.newFuncMethod,
    setNewFuncMethod: actions.setNewFuncMethod,
    openCreateDialog: actions.openCreateDialog,
    isRunning: runner.isRunning,
    output: runner.output,
    logs,
    activeFn: editor.activeFn,
    isActiveBuiltIn: editor.isActiveBuiltIn,
    isActivePackageFn: editor.isActivePackageFn,
    roleOptions,
    currentCode: editor.currentCode,
    getTestPayloadDisplay: editor.getTestPayloadDisplay,
    updateTestPayload: editor.updateTestPayload,
    initializeScriptDraft: editor.initializeScriptDraft,
    isDuplicateOpen: actions.isDuplicateOpen,
    duplicateSource: actions.duplicateSource,
    duplicateName: actions.duplicateName,
    setDuplicateName: actions.setDuplicateName,
    duplicateTags: actions.duplicateTags,
    setDuplicateTags: actions.setDuplicateTags,
    duplicateError: actions.duplicateError,
    openDuplicateDialog: actions.openDuplicateDialog,
    closeDuplicateDialog: actions.closeDuplicateDialog,
    confirmDuplicateToDraft: actions.confirmDuplicateToDraft,
    isDuplicating: actions.isDuplicating,
    isRenameOpen: actions.isRenameOpen,
    renameSource: actions.renameSource,
    renameName: actions.renameName,
    setRenameName: actions.setRenameName,
    renameTags: actions.renameTags,
    setRenameTags: actions.setRenameTags,
    renameError: actions.renameError,
    isRenaming: actions.isRenaming,
    openRenameDialog: actions.openRenameDialog,
    closeRenameDialog: actions.closeRenameDialog,
    confirmRenameFromList: actions.confirmRenameFromList,
    addLog,
    isSnippetInjected: editor.isSnippetInjected,
    injectSnippet: editor.injectSnippet,
    applySourceToEditor: editor.applySourceToEditor,
    aiOpen,
    setAiOpen,
    persistEdgeState: editor.persistEdgeState,
    updateActiveFunction: editor.updateActiveFunction,
    handleRun: runner.handleRun,
    handleCreateFunction: actions.handleCreateFunction,
    handleBulkApply: actions.handleBulkApply,
    handleCreateFromDraft: actions.handleCreateFromDraft,
    idToDelete: actions.idToDelete,
    setIdToDelete: actions.setIdToDelete,
    handleDeleteFunction: actions.handleDeleteFunction,
    confirmDelete: actions.confirmDelete,
    isCreatingFromDraft: actions.isCreatingFromDraft,
    filteredFunctions: catalog.filteredFunctions,
    groups: catalog.groups,
    getBoilerplate: editor.getBoilerplate,
    editorDocumentKey: editor.editorDocumentKey,
    toast,
    catalogQuery: catalog.catalogQuery,
    isCatalogLoading: catalog.catalogQuery.isLoading,
    isCatalogFetching: catalog.catalogQuery.isFetching,
    refreshCatalog: catalog.refreshCatalog,
    isUnusedFunctionsDialogOpen,
    setIsUnusedFunctionsDialogOpen,
  };
}

export type ServerFunctionsPageState = ReturnType<typeof useServerFunctionsPage>;
