/**
 * Sync IANA timezone options from zone1970.tab (IANA Time Zone Database).
 * Source: https://data.iana.org/time-zones/data/zone1970.tab
 *
 * Usage: npm run codegen:iana-timezones
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const IANA_ZONE1970_URL = 'https://data.iana.org/time-zones/data/zone1970.tab';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/shared/lib/ianaTimezoneOptions.generated.ts');

type TimezoneOption = { value: string; label: string };

function parseZone1970Tab(content: string): TimezoneOption[] {
  const zones = new Map<string, string>();

  for (const line of content.split('\n')) {
    if (!line || line.startsWith('#')) {
      continue;
    }

    const parts = line.split('\t');
    if (parts.length < 3) {
      continue;
    }

    const value = parts[2]?.trim();
    if (!value) {
      continue;
    }

    const comment = parts.slice(3).join(' ').trim();
    const label = comment ? `${value} — ${comment}` : value;
    zones.set(value, label);
  }

  return [...zones.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([value, label]) => ({ value, label }));
}

async function loadZone1970Tab(): Promise<string> {
  const response = await fetch(IANA_ZONE1970_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${IANA_ZONE1970_URL}: ${response.status} ${response.statusText}`);
  }

  return response.text();
}

function writeGeneratedFile(options: TimezoneOption[], sourceVersion: string): void {
  const serialized = options
    .map((option) => `  { value: ${JSON.stringify(option.value)}, label: ${JSON.stringify(option.label)} },`)
    .join('\n');

  const contents = `/* eslint-disable */\n/** Generated by \`npm run codegen:iana-timezones\` — do not edit. */\n/** Source: ${IANA_ZONE1970_URL} (${sourceVersion}) */\n\nexport type IanaTimezoneOption = { value: string; label: string };\n\nexport const IANA_ZONE1970_TIMEZONE_OPTIONS: IanaTimezoneOption[] = [\n${serialized}\n];\n`;

  fs.writeFileSync(outputPath, contents, 'utf8');
}

async function main(): Promise<void> {
  const content = await loadZone1970Tab();
  const options = parseZone1970Tab(content);
  const versionLine = content.split('\n').find((line) => line.includes('Paul Eggert')) ?? 'zone1970.tab';
  writeGeneratedFile(options, versionLine.replace(/^#\s*/, '').trim());
  console.log(`[codegen:iana-timezones] wrote ${options.length} zones to ${path.relative(root, outputPath)}`);
}

main().catch((error) => {
  console.error('[codegen:iana-timezones] failed:', error);
  process.exit(1);
});
