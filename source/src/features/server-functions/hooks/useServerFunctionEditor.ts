import { useCallback, useEffect, useRef, useState } from 'react';
import {
  useWorkspaceHorizontalSplitPanel,
  useWorkspaceVerticalSplitPanel,
  WORKSPACE_SPLIT_PANEL_KEYS,
} from '../../../shared/ui';
import { useUpdateBuiltinServerFunctionMutation, useUpdatePackageServerFunctionMutation, useUpdateServerFunctionMutation } from '../../../shared/api/queries/server-functions';
import { BUILTIN_FUNCTION_PERSISTABLE_KEYS } from '../../../shared/api/contracts/server-functions/constants';
import { isPackageServerFunction } from '../../../shared/api/contracts/server-functions/packageFunctions';
import { DEFAULT_SERVER_FUNCTION_LANGUAGE, EDGE_STATE_STORAGE_KEY } from '../constants';
import { createScriptDraftDefaults } from '../lib/scriptDraftDefaults';
import {
  markTestPayloadManual,
  resolveEffectiveTestPayloadJson,
} from '../../../shared/api/server-functions/buildFunctionDerivedMetadata';
import { buildManagedFunctionId } from '../../../core/functions/functionNaming';
import { buildBuiltinFunctionMetadataPayload, buildManagedFunctionPayload } from '../mappers';
import {
  normalizeServerFunctionFolder,
  normalizeServerFunctionName,
} from '../lib/duplicateServerFunctionIdentity';
import { buildServerFunctionTemplate } from '../templates';
import type { DraftFunctionState, ServerFunctionItem, InjectableSnippet } from '../types';
import { clearServerFunctionDraft, getServerFunctionDraft, mergeServerFunctionWithDraft, patchServerFunctionDraft } from './serverFunctionDraftCache';
import type { ServerFunctionCatalogState } from './useServerFunctionCatalog';
import { useServerFunctionDraft } from './useServerFunctionDraft';

type UseServerFunctionEditorInput = {
  catalog: ServerFunctionCatalogState;
  addLog: (msg: string, type?: 'info' | 'success' | 'warn') => void;
  showToast: (type: 'success' | 'error', text: string) => void;
  globalDefaultVMMode: 'v18.x' | 'v20.x';
  globalDefaultRAM: number;
  globalDefaultTimeout: number;
};

export function useServerFunctionEditor({
  catalog,
  addLog,
  showToast,
  globalDefaultVMMode,
  globalDefaultRAM,
  globalDefaultTimeout,
}: UseServerFunctionEditorInput) {
  const updateServerFunctionMutation = useUpdateServerFunctionMutation();
  const updateBuiltinServerFunctionMutation = useUpdateBuiltinServerFunctionMutation();
  const updatePackageServerFunctionMutation = useUpdatePackageServerFunctionMutation();
  const isSavingRef = useRef(false);

  const [draftFn, setDraftFn] = useState<DraftFunctionState>({
    name: '',
    folder: '',
    method: 'GET',
    code: buildServerFunctionTemplate('GET', '/api/hello-world', 'hello-world'),
    language: DEFAULT_SERVER_FUNCTION_LANGUAGE,
    testPayload: '{}',
    memoryLimit: 128,
    timeoutMs: 1500,
    runtimeVersion: 'v20.x',
    useGlobalConfig: true,
    enableLogs: true,
    cacheEnabled: false,
    cacheTtlMs: 3600000,
    cacheByParam: false,
    cacheByUser: false,
    engineType: 'SANDBOX_JS',
    metadataJson: null,
    accessControl: { allowRoles: [], allowUsers: [], denyRoles: [], denyUsers: [] },
  });
  const draftCodeIsAutoGeneratedRef = useRef(true);

  const containerRef = useRef<HTMLDivElement | null>(null);
  const column3Ref = useRef<HTMLDivElement | null>(null);
  const editorRef = useRef<any>(null);
  const injectMenuRef = useRef<HTMLDivElement | null>(null);
  const [isInjectMenuOpen, setIsInjectMenuOpen] = useState(false);

  const sidebarSplit = useWorkspaceVerticalSplitPanel({
    panelKey: WORKSPACE_SPLIT_PANEL_KEYS.serverFunctionsSidebar,
    defaultSize: 300,
    minSize: 180,
    maxSize: 580,
    measure: 'leading',
    containerRef,
    side: 'start',
  });
  const payloadSplit = useWorkspaceVerticalSplitPanel({
    panelKey: WORKSPACE_SPLIT_PANEL_KEYS.serverFunctionsPayload,
    defaultSize: 520,
    minSize: 240,
    maxSize: 650,
    measure: 'trailing',
    containerRef,
    side: 'end',
    defaultCollapsed: true,
  });

  const payloadHeightSplit = useWorkspaceHorizontalSplitPanel({
    panelKey: WORKSPACE_SPLIT_PANEL_KEYS.serverFunctionsPayloadHeight,
    defaultSize: 200,
    minSize: 100,
    maxSize: 600,
    measure: 'leading',
    containerRef: column3Ref,
    resolveSize: ({ clientY, rect }) => (
      Math.max(100, Math.min(rect.height - 148, clientY - rect.top))
    ),
  });

  const [isLargeScreen, setIsLargeScreen] = useState(false);

  const { activeId, catalogFunctions, functions, queryClient } = catalog;
  const catalogActiveFn = activeId ? (catalogFunctions.find((fn) => fn.id === activeId) ?? null) : null;
  const { patchDraft: patchActiveDraft } = useServerFunctionDraft(activeId, catalogActiveFn);

  const getDraftPath = (folder: string, name: string) => {
    const folderSlug = normalizeServerFunctionFolder(folder) || 'general';
    const nameSlug = normalizeServerFunctionName(name) || 'unnamed';
    return `/api/${folderSlug}/${nameSlug}`;
  };

  const resolveActiveFunction = (): ServerFunctionItem | null => {
    if (!activeId) {
      return null;
    }
    const catalogFn = catalogFunctions.find((fn) => fn.id === activeId);
    if (catalogFn) {
      return mergeServerFunctionWithDraft(catalogFn, getServerFunctionDraft(queryClient, activeId));
    }
    return functions.find((fn) => fn.id === activeId) ?? null;
  };

  const activeFn = resolveActiveFunction();
  const isActivePackageFn = activeFn ? isPackageServerFunction(activeFn) : false;
  const isActiveBuiltIn = !!activeFn?.isBuiltIn && !isActivePackageFn;
  const currentCode = activeId ? (activeFn?.code || '') : draftFn.code;
  const editorDocumentKey = activeId
    ? `active:${activeId}:${activeFn?.path ?? 'unknown'}`
    : `draft:${draftFn.method}:${getDraftPath(draftFn.folder, draftFn.name)}`;

  const getBoilerplate = (method: string, path: string) => buildServerFunctionTemplate(method, path);

  useEffect(() => {
    if (!draftFn.name) {
      setDraftFn((prev) => ({
        ...prev,
        memoryLimit: globalDefaultRAM,
        timeoutMs: globalDefaultTimeout,
        runtimeVersion: globalDefaultVMMode,
      }));
    }
  }, [draftFn.name, globalDefaultVMMode, globalDefaultRAM, globalDefaultTimeout]);

  useEffect(() => {
    if (activeId) {
      return;
    }

    if (!draftCodeIsAutoGeneratedRef.current) {
      return;
    }

    const nextPath = getDraftPath(draftFn.folder, draftFn.name);
    const nextCode = buildServerFunctionTemplate(draftFn.method, nextPath);

    setDraftFn((prev) => (prev.code === nextCode ? prev : { ...prev, code: nextCode }));
  }, [activeId, draftFn.folder, draftFn.name, draftFn.method]);

  useEffect(() => {
    const checkScreenSize = () => {
      setIsLargeScreen(typeof window !== 'undefined' && window.innerWidth >= 1280);
    };
    checkScreenSize();
    if (typeof window !== 'undefined') {
      window.addEventListener('resize', checkScreenSize);
      return () => window.removeEventListener('resize', checkScreenSize);
    }
  }, []);

  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (!injectMenuRef.current) return;
      if (!injectMenuRef.current.contains(event.target as Node)) {
        setIsInjectMenuOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const toggleSidebar = sidebarSplit.toggle;
  const togglePayload = payloadSplit.toggle;

  const updateActiveFunction = (updatedFields: Partial<ServerFunctionItem>) => {
    if (!activeId) {
      return;
    }
    const target = catalogFunctions.find((fn) => fn.id === activeId);
    if (!target) {
      return;
    }
    if (target.isBuiltIn) {
      const allowedBuiltInKeys = new Set<string>(BUILTIN_FUNCTION_PERSISTABLE_KEYS);
      const disallowedKeys = Object.keys(updatedFields).filter((key) => !allowedBuiltInKeys.has(key));
      if (disallowedKeys.length > 0) {
        return;
      }
      patchServerFunctionDraft(catalog.queryClient, activeId, updatedFields);
      catalog.bumpDraftRevision();
      return;
    }
    patchActiveDraft(updatedFields);
    catalog.bumpDraftRevision();
  };

  const resolvePayloadContext = () => {
    if (activeId && activeFn) {
      return {
        code: currentCode,
        method: activeFn.method,
        path: activeFn.path,
        testPayload: activeFn.testPayload,
        metadataJson: activeFn.metadataJson,
      };
    }

    return {
      code: draftFn.code,
      method: draftFn.method,
      path: getDraftPath(draftFn.folder, draftFn.name),
      testPayload: draftFn.testPayload,
      metadataJson: draftFn.metadataJson,
    };
  };

  const getTestPayloadDisplay = () => {
    const context = resolvePayloadContext();
    return resolveEffectiveTestPayloadJson(context);
  };

  const updateTestPayload = (payloadJson: string) => {
    const context = resolvePayloadContext();
    const metadataRecord = markTestPayloadManual(context.metadataJson);

    if (activeId) {
      updateActiveFunction({
        testPayload: payloadJson,
        metadataJson: metadataRecord as ServerFunctionItem['metadataJson'],
      });
      return;
    }

    setDraftFn((prev) => ({
      ...prev,
      testPayload: payloadJson,
      metadataJson: metadataRecord as DraftFunctionState['metadataJson'],
    }));
  };

  const resetScriptDraft = useCallback(() => {
    draftCodeIsAutoGeneratedRef.current = true;
    setDraftFn({
      name: '',
      folder: '',
      method: 'GET',
      code: buildServerFunctionTemplate('GET', '/api/hello-world', 'hello-world'),
      language: DEFAULT_SERVER_FUNCTION_LANGUAGE,
      testPayload: '{}',
      memoryLimit: globalDefaultRAM,
      timeoutMs: globalDefaultTimeout,
      runtimeVersion: globalDefaultVMMode,
      useGlobalConfig: true,
      enableLogs: true,
      cacheEnabled: false,
      cacheTtlMs: 3600000,
      cacheByParam: false,
      cacheByUser: false,
      accessControl: { allowRoles: [], allowUsers: [], denyRoles: [], denyUsers: [] },
      ...createScriptDraftDefaults(),
    });
  }, [globalDefaultRAM, globalDefaultTimeout, globalDefaultVMMode]);

  const initializeScriptDraft = () => {
    resetScriptDraft();
    catalog.setActiveId(null, { isNewDraft: true });
  };

  useEffect(() => {
    if (!catalog.isNewDraftRoute || catalog.activeId) {
      return;
    }

    resetScriptDraft();
  }, [catalog.activeId, catalog.isNewDraftRoute, resetScriptDraft]);

  const isSnippetInjected = (snippet: InjectableSnippet) => currentCode.includes(snippet.marker);

  const applyCodeUpdate = (nextCode: string) => {
    if (activeId) {
      updateActiveFunction({ code: nextCode });
      return;
    }
    setDraftFn((prev) => ({ ...prev, code: nextCode }));
  };

  const injectSnippet = (snippet: InjectableSnippet) => {
    if (isSnippetInjected(snippet)) {
      addLog(`"${snippet.label}" already exists in this function.`, 'warn');
      return;
    }

    setIsInjectMenuOpen(false);

    const editor = editorRef.current;
    if (editor) {
      const model = editor.getModel?.();
      const selection = editor.getSelection?.();
      if (model && selection) {
        editor.executeEdits('inject-snippet', [
          {
            range: selection,
            text: `${snippet.body}\n`,
            forceMoveMarkers: true,
          },
        ]);
        editor.focus?.();
        addLog(`Injected "${snippet.label}" into active editor.`, 'success');
        return;
      }
    }

    const separator = currentCode.trim().length > 0 ? '\n\n' : '';
    applyCodeUpdate(`${currentCode}${separator}${snippet.body}\n`);
    addLog(`Injected "${snippet.label}" into function source.`, 'success');
  };

  const applySourceToEditor = (nextCode: string) => {
    if (isActiveBuiltIn) {
      throw new Error('Built-in routes cannot be edited.');
    }
    draftCodeIsAutoGeneratedRef.current = false;
    const editor = editorRef.current;
    const model = editor?.getModel?.();
    if (model && typeof editor.executeEdits === 'function') {
      editor.executeEdits('ai-apply-source', [
        {
          range: model.getFullModelRange(),
          text: nextCode,
          forceMoveMarkers: true,
        },
      ]);
      editor.focus?.();
      return;
    }
    applyCodeUpdate(nextCode);
  };

  const persistEdgeState = async () => {
    if (isSavingRef.current) {
      return false;
    }

    try {
      const payload = {
        globalDefaultVMMode,
        globalDefaultRAM,
        globalDefaultTimeout,
      };
      localStorage.setItem(EDGE_STATE_STORAGE_KEY, JSON.stringify(payload));

      if (activeFn && isPackageServerFunction(activeFn)) {
        isSavingRef.current = true;
        const fnToSave = resolveActiveFunction() ?? activeFn;
        const { response, data } = await updatePackageServerFunctionMutation.mutateAsync({
          id: fnToSave.id,
          payload: { code: fnToSave.code },
        });

        if (!response.ok) {
          throw new Error(data?.error || 'Failed to persist package API changes.');
        }

        catalog.upsertCatalogFunction(fnToSave);
        clearServerFunctionDraft(catalog.queryClient, fnToSave.id);
        catalog.bumpDraftRevision();
        addLog('Saved package API handler to installed package runtime.', 'success');
        showToast('success', `Saved ${fnToSave.path}`);
      } else if (activeFn && !activeFn.isBuiltIn) {
        isSavingRef.current = true;
        const fnToSave = resolveActiveFunction() ?? activeFn;
        const previousId = fnToSave.id;
        const nextId = buildManagedFunctionId(fnToSave.folder, fnToSave.name);
        const savedFn = nextId === previousId ? fnToSave : { ...fnToSave, id: nextId };

        const { response, data } = await updateServerFunctionMutation.mutateAsync({
          id: previousId,
          payload: buildManagedFunctionPayload(fnToSave),
        });

        if (!response.ok) {
          throw new Error(data?.error || 'Failed to persist function settings.');
        }

        if (nextId !== previousId) {
          catalog.replaceCatalogFunctionIdentity(previousId, savedFn);
          catalog.setActiveId(nextId);
        } else {
          catalog.upsertCatalogFunction(savedFn);
        }
        clearServerFunctionDraft(catalog.queryClient, previousId);
        catalog.bumpDraftRevision();
        addLog('Saved edge configuration to workspace/server-functions/custom.', 'success');
        showToast('success', `Saved ${savedFn.path}`);
      } else if (activeFn?.isBuiltIn) {
        isSavingRef.current = true;
        const fnToSave = resolveActiveFunction() ?? activeFn;
        const { response, data } = await updateBuiltinServerFunctionMutation.mutateAsync({
          id: fnToSave.id,
          payload: buildBuiltinFunctionMetadataPayload(fnToSave),
        });

        if (!response.ok) {
          throw new Error(data?.error || 'Failed to persist built-in function settings.');
        }

        catalog.upsertCatalogFunction(fnToSave);
        clearServerFunctionDraft(catalog.queryClient, fnToSave.id);
        catalog.bumpDraftRevision();
        addLog('Saved built-in function metadata to workspace/server-functions/builtin.', 'success');
        showToast('success', `Saved ${fnToSave.path}`);
      } else {
        addLog('Saved local edge runner defaults.', 'success');
        showToast('success', 'Saved edge runner defaults.');
      }

      return true;
    } catch (error: any) {
      const message = error?.message || 'Failed to save edge configuration changes.';
      addLog(message, 'warn');
      showToast('error', message);
      return false;
    } finally {
      isSavingRef.current = false;
    }
  };

  return {
    draftFn,
    setDraftFn,
    draftCodeIsAutoGeneratedRef,
    getDraftPath,
    getBoilerplate,
    containerRef,
    column3Ref,
    editorRef,
    injectMenuRef,
    isInjectMenuOpen,
    setIsInjectMenuOpen,
    sidebarWidth: sidebarSplit.size,
    payloadWidth: payloadSplit.size,
    payloadHeight: payloadHeightSplit.size,
    isResizingSidebar: sidebarSplit.isResizing,
    isResizingPayload: payloadSplit.isResizing,
    isResizingPayloadHeight: payloadHeightSplit.isResizing,
    isLargeScreen,
    toggleSidebar,
    togglePayload,
    payloadCollapsed: payloadSplit.collapsed,
    sidebarSplitHandleProps: sidebarSplit.splitHandleProps,
    payloadSplitHandleProps: payloadSplit.splitHandleProps,
    payloadHeightSplitHandleProps: payloadHeightSplit.splitHandleProps,
    activeFn,
    isActiveBuiltIn,
    isActivePackageFn,
    getTestPayloadDisplay,
    updateTestPayload,
    initializeScriptDraft,
    currentCode,
    updateActiveFunction,
    isSnippetInjected,
    injectSnippet,
    applySourceToEditor,
    persistEdgeState,
    editorDocumentKey,
  };
}

export type ServerFunctionEditorState = ReturnType<typeof useServerFunctionEditor>;
