export const renderUrlParamsRecordLiteral = (urlParams: Record<string, string>): string => {
  const entries = Object.entries(urlParams);
  if (entries.length === 0) {
    return '{}';
  }

  return `{ ${entries.map(([key, path]) => `${JSON.stringify(key)}: ${JSON.stringify(path)}`).join(', ')} }`;
};

export const renderHeadersRecordLiteral = (headers: Record<string, string>): string => {
  const entries = Object.entries(headers);
  if (entries.length === 0) {
    return '{}';
  }

  return `{ ${entries.map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(', ')} }`;
};

export const renderFetchUrlExpression = (
  endpointTemplate: string,
  urlParams: Record<string, string>,
  contextVar = BINDING_CONTEXT_VAR,
): string =>
  `resolveBindingUrl(${JSON.stringify(endpointTemplate)}, ${contextVar}, ${renderUrlParamsRecordLiteral(urlParams)})`;

export const renderFetchHeadersExpression = (
  headers: Record<string, string>,
  urlParams: Record<string, string>,
  contextVar = BINDING_CONTEXT_VAR,
): string =>
  `resolveBindingHeaders(${contextVar}, ${renderHeadersRecordLiteral(headers)}, ${renderUrlParamsRecordLiteral(urlParams)})`;

export const renderMutationUrlExpression = (
  endpointTemplate: string,
  urlParams: Record<string, string>,
): string =>
  `resolveBindingUrl(${JSON.stringify(endpointTemplate)}, ${BINDING_CONTEXT_VAR}, ${renderUrlParamsRecordLiteral(urlParams)})`;

export const renderMutationHeadersExpression = (
  headers: Record<string, string>,
  urlParams: Record<string, string>,
  includeJsonContentType = true,
): string => {
  if (!includeJsonContentType) {
    return renderFetchHeadersExpression(headers, urlParams);
  }

  return `{ ...${renderFetchHeadersExpression(headers, urlParams)}, 'Content-Type': 'application/json' }`;
};

export const renderBindingContextInitialization = (options?: {
  dataContextVar?: string;
  storeVar?: string;
}): string[] => {
  const dataContextVar = options?.dataContextVar;
  const storeVar = options?.storeVar;

  if (!dataContextVar && !storeVar) {
    return [`  const ${BINDING_CONTEXT_VAR} = React.useMemo<Record<string, unknown>>(() => ({}), []);`];
  }

  const spreads: string[] = [];
  const deps: string[] = [];

  if (dataContextVar) {
    spreads.push(
      `...(typeof ${dataContextVar} === 'object' && ${dataContextVar} !== null ? ${dataContextVar} as Record<string, unknown> : {})`,
    );
    deps.push(dataContextVar);
  }

  if (storeVar) {
    spreads.push(
      `...(typeof ${storeVar} === 'object' && ${storeVar} !== null ? ${storeVar} as Record<string, unknown> : {})`,
    );
    deps.push(storeVar);
  }

  return [
    `  const ${BINDING_CONTEXT_VAR} = React.useMemo<Record<string, unknown>>(() => ({ ${spreads.join(', ')} }), [${deps.join(', ')}]);`,
  ];
};

export const renderNestedPayloadMappingLines = (
  payloadMapping: Record<string, string>,
  valueExpression: string,
  indent = '      ',
): string[] => {
  const lines: string[] = [];
  lines.push(`${indent}const payload: Record<string, unknown> = {};`);

  for (const [apiPath, sourceField] of Object.entries(payloadMapping)) {
    const resolvedValue = valueExpression.replace('SOURCE_FIELD', JSON.stringify(sourceField));
    if (isNestedPayloadPath(apiPath)) {
      lines.push(`${indent}setNestedPayloadValue(payload, ${JSON.stringify(apiPath)}, ${resolvedValue});`);
    } else {
      lines.push(`${indent}payload[${JSON.stringify(apiPath)}] = ${resolvedValue};`);
    }
  }

  return lines;
};
