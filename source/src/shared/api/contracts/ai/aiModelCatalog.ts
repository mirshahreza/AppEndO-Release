import type { AiModelCapabilities, AiModelEntry } from './types';

const DEFAULT_CAPABILITIES: AiModelCapabilities = {
  chat: true,
  streaming: true,
  vision: false,
  tools: false,
  embeddings: false,
  imageGeneration: false,
  speechToText: false,
  textToSpeech: false,
};

const caps = (overrides: Partial<AiModelCapabilities>): AiModelCapabilities => ({
  ...DEFAULT_CAPABILITIES,
  ...overrides,
});

type PresetInput = Omit<AiModelEntry, 'capabilities'> & {
  capabilities?: Partial<AiModelCapabilities>;
};

const preset = (entry: PresetInput): AiModelEntry => ({
  ...entry,
  capabilities: caps(entry.capabilities ?? {}),
});

