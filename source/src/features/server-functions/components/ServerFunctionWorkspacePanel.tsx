import React from 'react';
import { ErrorBoundary } from '../../../components/ui/ErrorBoundary';
import type { ServerFunctionsPageState } from '../hooks/useServerFunctionsPage';
import { getActiveSourceLanguage } from '../templates';
import { MonacoEditorPanel, setupEdgeCodeEditorOnMount } from './MonacoEditorPanel';

export type SandboxEditorPanelProps = {
  page: ServerFunctionsPageState;
};

export const SandboxEditorPanel: React.FC<SandboxEditorPanelProps> = ({ page }) => {
  const {
    activeId,
    activeFn,
    draftFn,
    setDraftFn,
    draftCodeIsAutoGeneratedRef,
    isActiveBuiltIn,
    updateActiveFunction,
    editorRef,
    editorDocumentKey,
  } = page;

  return (
    <ErrorBoundary
      context="ServerFunctionsMonaco"
      title="Code editor failed to load"
      fallbackClassName="flex h-full min-h-0 w-full flex-1 items-center justify-center p-4"
    >
      <MonacoEditorPanel
        documentKey={editorDocumentKey}
        defaultLanguage="typescript"
        language={getActiveSourceLanguage(activeId ? activeFn?.language : draftFn.language) === 'js' ? 'javascript' : 'typescript'}
        value={activeId ? (activeFn?.code || '') : draftFn.code}
        onMount={(editor, monaco) => {
          editorRef.current = editor;
          setupEdgeCodeEditorOnMount(editor, monaco);
        }}
        onChange={(val) => {
          if (activeId) {
            updateActiveFunction({ code: val || '' });
            return;
          }
          draftCodeIsAutoGeneratedRef.current = false;
          setDraftFn((prev) => ({ ...prev, code: val || '' }));
        }}
        options={{
          fontSize: 12,
          fontFamily: '"JetBrains Mono", "Fira Code", monospace',
          minimap: { enabled: false },
          lineNumbers: 'on',
          scrollBeyondLastLine: false,
          automaticLayout: true,
          tabSize: 2,
          padding: { top: 12, bottom: 12 },
          wordWrap: 'on',
          domReadOnly: false,
          readOnly: isActiveBuiltIn,
          links: false,
        }}
      />
    </ErrorBoundary>
  );
};

export const resolveWorkspaceEngineType = (page: ServerFunctionsPageState): 'SANDBOX_JS' | 'DATA_API' => {
  if (page.activeId) {
    return page.activeFn?.engineType === 'DATA_API' ? 'DATA_API' : 'SANDBOX_JS';
  }
  return page.draftFn.engineType === 'DATA_API' ? 'DATA_API' : 'SANDBOX_JS';
};
