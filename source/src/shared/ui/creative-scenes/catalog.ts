function meta(
  value: Omit<CreativeSceneMeta, 'siteCompatible' | 'appCompatible'>,
): CreativeSceneMeta {
  return {
    ...value,
    siteCompatible: true,
    appCompatible: APP_IDS.has(value.id),
  };
}

