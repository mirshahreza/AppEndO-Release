/**
 * Regression test for a real user-reported bug: "الان به درستی ادرس api و ساخت و اینجور چیزا رو
 * درست انجام نمیده و باگ داره" — the Auto Form / Auto Table "generate from API"
 * wizards did not correctly call the picked API endpoint at runtime.
 *
 * Root cause: `buildDefaultRestOperations` (bindingResourceModel.ts) generates REST-convention
 * detail/update/delete endpoints using `:id`-style path params (e.g. `/api/orders/:id`) for any
 * data source built from a picked endpoint via `buildDataSourceFromEndpoint` — used by Auto Form
 * and Auto Table wizards. A region bound to
 * that data source with `loadOperation: 'detail'` (Auto Form "Edit existing" / "Save form" /
 * "View only") has its
 * GET load resolved — both in the exported/published app (`bindingCodegen.ts` /
 * `bindingApiCodegen.ts`) and via the shared runtime helper (`bindingMutationRuntime.ts`) — through
 * `resolveBindingUrl`, which only ever substituted `{id}`-style placeholders. The `:id` token was
 * therefore left completely unresolved in the request URL, and the (correctly extracted) `id`
 * param was instead appended as a stray query string — e.g. `/api/orders/:id?id=123` instead of
 * the working `/api/orders/123`. Every published Edit/Detail form generated by these wizards would
 * 404 (or hit the wrong route) the moment it tried to load the record to edit/view.
 */
import { describe, expect, it } from 'vitest';
import { transformSync } from 'esbuild';
import { buildAutoFormDocument, type AutoFormBuildConfig } from '../autoFormTemplateBuilder';
import { buildDataSourceFromEndpoint } from '../bindingResourceModel';
import { generateDesignerTsx } from '../codegen';
import { resolveBindingUrl } from '../bindingMutationRuntime';

const buildEditFormConfig = (): AutoFormBuildConfig => {
  const dataSource = buildDataSourceFromEndpoint('/api/orders', {
    fields: ['id', 'customerName', 'total'],
    primaryKey: 'id',
    method: 'PUT',
  });

  return {
    title: 'Orders form',
    includeTitle: true,
    dataSource,
    scenario: 'edit',
    fields: [
      {
        field: { name: 'customerName', type: 'string', location: 'body', required: false },
        enabled: true,
        label: 'Customer Name',
        controlPaletteItemId: 'heroui.input',
      },
    ],
    submitLabel: 'Update',
    successBehaviors: ['refresh', 'toast'],
    layout: 'single',
    detailIdSource: 'selection',
  };
};

describe('Auto Form/CRUD wizard: colon-style detail endpoint resolves correctly at export time', () => {
  it('generates a detail data source using the :id REST convention (sanity check on the shared builder)', () => {
    const dataSource = buildDataSourceFromEndpoint('/api/orders', {
      fields: ['id'],
      primaryKey: 'id',
      method: 'PUT',
    });
    expect(dataSource.operations.detail?.endpoint).toBe('/api/orders/:id');
  });

  it('the exported app resolves the :id-based region GET load to a real url at runtime (not a literal ":id?id=…" string)', () => {
    const built = buildAutoFormDocument(buildEditFormConfig());
    const tsx = generateDesignerTsx(built.document, built.bindingDefinitions);

    // The exported region fetch must call resolveBindingUrl with the raw endpoint template …
    expect(tsx).toContain('resolveBindingUrl("/api/orders/:id", designerStore, { "id": "selection.id" })');

    // … and the SAME resolveBindingUrl implementation emitted into the exported file must be able
    // to actually resolve that template, not just pass it through unresolved.
    const helperStart = tsx.indexOf('const resolveBindingUrl');
    expect(helperStart).toBeGreaterThan(-1);
    const helperEnd = tsx.indexOf('\n};', helperStart) + 3;
    const helperSourceTs = tsx.slice(helperStart, helperEnd);
    const helperSource = transformSync(helperSourceTs, { loader: 'ts' }).code;

    // eslint-disable-next-line no-new-func -- executing the exact source the export writes to disk
    const compiledResolveBindingUrl = new Function(
      'readBindingParamValue',
      `${helperSource}\nreturn resolveBindingUrl;`,
    )((context: Record<string, unknown>, dataPath: string) => (
      dataPath.split('.').reduce<unknown>((cursor, segment) => (
        cursor && typeof cursor === 'object' ? (cursor as Record<string, unknown>)[segment] : undefined
      ), context)
    ));

    const resolvedUrl = compiledResolveBindingUrl(
      '/api/orders/:id',
      { selection: { id: '123' } },
      { id: 'selection.id' },
    );

    expect(resolvedUrl).toBe('/api/orders/123');
    expect(resolvedUrl).not.toContain(':id');
    expect(resolvedUrl).not.toContain('?id=');
  });

  it('resolveBindingUrl (shared runtime helper used by preview + Auto Form static submit) resolves :id directly', () => {
    const url = resolveBindingUrl('/api/orders/:id', { selection: { id: '123' } }, { id: 'selection.id' });
    expect(url).toBe('/api/orders/123');
  });

  /**
   * Create-only Auto Forms bind a region data source but never set `loadOperation`.
   * They must not register a background GET (which used to hit `/api/base-info` or
   * unresolved `/api/users/:id` and surface as Hydration request failed (404) on refresh).
   */
  it('a Create-only form does not register a background region GET on mount', () => {
    const dataSource = buildDataSourceFromEndpoint('/api/users', {
      fields: ['id', 'name'],
      primaryKey: 'id',
      method: 'POST',
    });
    const built = buildAutoFormDocument({
      title: 'Create user',
      includeTitle: true,
      dataSource,
      scenario: 'create',
      fields: [
        {
          field: { name: 'name', type: 'string', location: 'body', required: true },
          enabled: true,
          label: 'Name',
          controlPaletteItemId: 'heroui.input',
        },
      ],
      submitLabel: 'Create',
      successBehaviors: ['refresh'],
      layout: 'single',
    });
    const tsx = generateDesignerTsx(built.document, built.bindingDefinitions);

    expect(tsx).not.toContain('resolveBindingUrl("/api/users/:id"');
    expect(tsx).not.toMatch(/useDataFetch<[^>]+>\([^)]*\/api\/users\/:id/);
  });
});
