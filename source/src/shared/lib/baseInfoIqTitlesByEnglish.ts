export function resolveBaseInfoIqCanonicalTitle(
  cultureId: string,
  canonical: string | null | undefined,
): string | undefined {
  if (cultureId.trim() !== 'iq') {
    return undefined;
  }

  const trimmed = String(canonical ?? '').trim();
  if (!trimmed) {
    return undefined;
  }

  return BASE_INFO_IQ_TITLES_BY_ENGLISH[trimmed];
}
