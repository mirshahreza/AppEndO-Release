export const isVizPaletteItemId = (itemId: string | null | undefined): itemId is VizPaletteItemId =>
  typeof itemId === 'string' && (VIZ_PALETTE_ITEM_IDS as readonly string[]).includes(itemId);

export const isVizChartPaletteItemId = (itemId: string | null | undefined): boolean =>
  typeof itemId === 'string' && (itemId === 'viz.chart' || itemId.startsWith('viz.chart-'));

export const isVizMapPaletteItemId = (itemId: string | null | undefined): boolean =>
  typeof itemId === 'string' && (itemId === 'viz.map-pin' || itemId === 'viz.map-choropleth');

