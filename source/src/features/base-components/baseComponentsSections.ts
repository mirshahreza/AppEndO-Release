export function getBaseComponentsSectionGroup(id: BaseComponentsSectionGroupId): BaseComponentsSectionGroup {
  const group = BASE_COMPONENTS_SECTION_GROUPS.find((entry) => entry.id === id);
  if (!group) {
    throw new Error(`Unknown Base Components section group: ${id}`);
  }
  return group;
}
