const DEFAULT_UI_SLOT = 'core.dashboard.widgets';

const toSlug = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'item';

const ensureRelativePath = (value: string, fallback: string) => {
  const clean = value.trim().replace(/^\/+/, '');
  if (!clean) return fallback;
  return clean;
};

const buildApiStub = (api: { method: string; path: string }) =>
  `// Generated by Package Repack\n// ${api.method} ${api.path}\n\nexport default async function handler(req: any, res: any) {\n  return res.json({\n    success: true,\n    package: true,\n    method: '${api.method}',\n    path: '${api.path}',\n    timestamp: new Date().toISOString(),\n  });\n}\n`;

const buildUiStub = (componentKey: string) =>
  `import React from 'react';\n\nexport const ${componentKey.replace(/[^a-zA-Z0-9]/g, '_')} = () => {\n  return <div>Generated component: ${componentKey}</div>;\n};\n\nexport default ${componentKey.replace(/[^a-zA-Z0-9]/g, '_')};\n`;

export const REPACK_ADDON_INSTALL_SQL_ENTRY = 'db/install/repack-addon.sql';
export const REPACK_ADDON_UNINSTALL_SQL_ENTRY = 'db/uninstall/repack-addon.sql';
export const REPACK_ADDON_OPTIONAL_INSTALL_SQL_ENTRY = 'db/seed/repack-addon-optional-records.sql';
export const REPACK_ADDON_OPTIONAL_UNINSTALL_SQL_ENTRY = 'db/uninstall/repack-addon-optional-records.sql';

export type BuildPackageRepackAdditionsInput = {
  packageId: string;
  existingManifest: PackageBundleManifest | null;
  selectedApis: PackageBuilderCatalogApiItem[];
  selectedComponents: PackageBuilderCatalogUiComponentItem[];
  selectedPortals: ExperienceManifestPortal[];
  selectedWorkflows: PackageBuilderCatalogWorkflowItem[];
  catalogNavigations: NavigationManifestSummary[];
  pageSeedComponents?: PackageBuilderCatalogUiComponentItem[];
  skipUiRouteComponentKeys?: readonly string[];
  installSql: string;
  uninstallSql: string;
  includeInitialRecords?: boolean;
  optionalInstallSql?: string;
  optionalUninstallSql?: string;
};

export function countPackageRepackAdditionSelections(input: {
  selectedApis: PackageBuilderCatalogApiItem[];
  selectedComponents: PackageBuilderCatalogUiComponentItem[];
  selectedPortals: ExperienceManifestPortal[];
  selectedWorkflows: PackageBuilderCatalogWorkflowItem[];
  selectedEdgeModels?: number;
  selectedEdgeApis?: number;
  installSql: string;
  includeInitialRecords?: boolean;
  optionalInstallSql?: string;
}): number {
  const includeOptional = input.includeInitialRecords !== false
    && Boolean(input.optionalInstallSql?.trim());
  return input.selectedApis.length
    + input.selectedComponents.length
    + input.selectedPortals.length
    + input.selectedWorkflows.length
    + (input.selectedEdgeModels ?? 0)
    + (input.selectedEdgeApis ?? 0)
    + (input.installSql.trim().length > 0 ? 1 : 0)
    + (includeOptional ? 1 : 0);
}

export function areRepackSqlScriptsPaired(installSql: string, uninstallSql: string): boolean {
  const hasInstallSql = installSql.trim().length > 0;
  const hasUninstallSql = uninstallSql.trim().length > 0;
  return hasInstallSql === hasUninstallSql;
}

export function buildPackageRepackAdditions(
  input: BuildPackageRepackAdditionsInput,
): PackageRepackAdditionsPayload | null {
  const {
    packageId,
    existingManifest,
    selectedApis,
    selectedComponents,
    selectedPortals,
    selectedWorkflows,
    catalogNavigations,
    pageSeedComponents,
    skipUiRouteComponentKeys,
    installSql,
    uninstallSql,
    includeInitialRecords = true,
    optionalInstallSql = '',
    optionalUninstallSql = '',
  } = input;

  const existingApiIds = new Set((existingManifest?.capabilities.apis ?? []).map((api) => api.id));
  const existingApiPaths = new Set((existingManifest?.capabilities.apis ?? []).map((api) => api.path));
  const existingComponentKeys = new Set(
    readManifestCapabilityArray(existingManifest?.capabilities.ui_components).map((item) => item.componentKey),
  );
  const existingPortalSegments = new Set(
    ((existingManifest as PackageBundleManifest & {
      capabilities: { portals?: Array<{ segment: string }> };
    })?.capabilities.portals ?? []).map((portal) => portal.segment),
  );
  const existingNavigationIds = new Set(
    ((existingManifest as PackageBundleManifest & {
      capabilities: { navigations?: Array<{ id: string }> };
    })?.capabilities.navigations ?? []).map((navigation) => navigation.id),
  );
  const existingWorkflowIds = new Set(
    (existingManifest?.capabilities.workflows ?? []).map((workflow) => (
      packageWorkflowIdentity(workflow.scopeKey, workflow.key)
    )),
  );
  const existingUiRoutePageKeys = new Set(
    ((existingManifest as PackageBundleManifest & {
      capabilities: { ui_routes?: Array<{ pageKey: string }> };
    })?.capabilities.ui_routes ?? []).map((route) => route.pageKey),
  );

  const files: PackageRepackAdditionsPayload['files'] = [];
  const addFile = (entryPath: string, content: string) => {
    files.push({ entryPath, content });
  };

  const usedApiSlugs = new Set<string>();
  const apis = selectedApis
    .filter((api) => !existingApiIds.has(api.id) && !existingApiPaths.has(api.path))
    .map((api, index) => {
      const apiSlug = allocateUniquePackageApiRouteSuffix(
        buildPackageApiSlug({
          folder: api.folder,
          name: api.name,
          path: api.path,
        }),
        usedApiSlugs,
      );
      const mapping = buildManagedFunctionPackageApiMapping({
        packageId,
        folder: api.folder,
        name: api.name,
        method: api.method,
        path: api.path,
        apiSlug,
      });
      const bundle = api.exportBundle;
      if (bundle) {
        addFile(mapping.entry, bundle.code);
        addFile(resolveApiMetaEntryPath(mapping.entry), bundle.metaJson);
      } else {
        addFile(mapping.entry, buildApiStub({ method: api.method, path: api.path }));
      }
      return {
        id: `${toSlug(api.method)}-${apiSlug}-${index + 1}`,
        method: api.method,
        path: mapping.manifestPath,
        entry: mapping.entry,
        timeoutMs: bundle?.timeoutMs ?? 10000,
        auth: (bundle?.auth ?? 'admin') as 'public' | 'authenticated' | 'admin',
      };
    });

  const ui_components = selectedComponents
    .filter((item) => !existingComponentKeys.has(item.componentKey))
    .map((item, index) => {
      const bundle = item.exportBundle;
      const entry = ensureRelativePath(
        '',
        bundle?.entry ?? buildPackageUiEntryPath(item.componentKey),
      );
      addFile(entry, bundle?.code ?? buildUiStub(item.componentKey));
      if (bundle?.draftJson) {
        const draftEntry = bundle.draftEntry ?? buildPackageDesignerPageDraftEntry(item.componentKey);
        addFile(draftEntry, bundle.draftJson);
        return {
          componentKey: item.componentKey,
          slotId: DEFAULT_UI_SLOT,
          entry,
          order: 100 + index,
          designerDraftId: item.id,
          draftEntry,
        };
      }
      return {
        componentKey: item.componentKey,
        slotId: DEFAULT_UI_SLOT,
        entry,
        order: 100 + index,
        designerDraftId: item.id,
      };
    });

  const portals = selectedPortals
    .filter((portal) => !existingPortalSegments.has(portal.segment))
    .map((portal) => {
      const entry = `platform/portals/${toSlug(portal.segment)}.json`;
      addFile(entry, `${JSON.stringify(portal, null, 2)}\n`);
      return {
        segment: portal.segment,
        entry,
      };
    });

  const portalNavigations = resolveNavigationsForPortals(selectedPortals, catalogNavigations);

  const navigations = portalNavigations
    .filter((navigation) => !existingNavigationIds.has(navigation.id))
    .map((navigation) => {
      const entry = `platform/navigations/${toSlug(navigation.id)}.json`;
      const { builtIn: _builtIn, groupCount: _groupCount, itemCount: _itemCount, ...payload } = navigation;
      addFile(entry, `${JSON.stringify(payload, null, 2)}\n`);
      return {
        id: navigation.id,
        entry,
      };
    });

  const workflows = selectedWorkflows
    .filter((workflow) => !existingWorkflowIds.has(packageWorkflowIdentity(workflow.scopeKey, workflow.key)))
    .map((workflow) => ({
      scopeKey: workflow.scopeKey,
      key: workflow.key,
      entry: packageWorkflowEntryPath(workflow.scopeKey, workflow.key),
    }));

  const ui_routes = buildPackageUiRoutesForPageSeeds({
    pageSeeds: pageSeedComponents ?? selectedComponents,
    skipComponentKeys: new Set(skipUiRouteComponentKeys ?? []),
  }).filter((route) => !existingUiRoutePageKeys.has(route.pageKey));

  const existingUiRoutes = ((existingManifest as PackageBundleManifest & {
    capabilities: {
      ui_routes?: Array<{
        pageKey: string;
        entry: string;
        suggestedRoutePattern?: string;
        suggestedMountId?: string;
      }>;
    };
  })?.capabilities.ui_routes ?? []);
  const allStudioRoutes: Array<{
    pageKey: string;
    entry: string;
    suggestedRoutePattern?: string;
    suggestedMountId?: string;
  }> = [];
  const seenStudioPageKeys = new Set<string>();
  for (const route of [...existingUiRoutes, ...ui_routes]) {
    if (seenStudioPageKeys.has(route.pageKey)) continue;
    seenStudioPageKeys.add(route.pageKey);
    allStudioRoutes.push(route);
  }
  const studioModuleExtras = ui_routes.length > 0
    ? buildPackageStudioModuleExtras({
      packageName: existingManifest?.name ?? packageId,
      routes: allStudioRoutes,
      pageSeeds: pageSeedComponents ?? selectedComponents,
    })
    : null;
  if (studioModuleExtras) {
    for (const extra of studioModuleExtraFiles(studioModuleExtras)) {
      addFile(extra.entry, extra.content);
    }
  }
  if (shouldPackPublicSiteHomePortal(packageId)) {
    const homePortal = publicSiteHomePortalArtifactFile();
    addFile(homePortal.entry, homePortal.content);
  }

  const db_objects: NonNullable<PackageRepackAdditionsPayload['db_objects']> = [];
  const objectNameBase = packageId.replace(/[^a-z0-9_]/g, '_').slice(0, 80) || 'package';
  if (installSql.trim()) {
    const uninstallEntry = uninstallSql.trim() ? REPACK_ADDON_UNINSTALL_SQL_ENTRY : undefined;
    addFile(REPACK_ADDON_INSTALL_SQL_ENTRY, `${installSql.trim()}\n`);
    if (uninstallEntry) {
      addFile(uninstallEntry, `${uninstallSql.trim()}\n`);
    }
    db_objects.push({
      objectType: 'seed',
      objectName: `${objectNameBase}_repack_addon`,
      installScript: REPACK_ADDON_INSTALL_SQL_ENTRY,
      uninstallScript: uninstallEntry,
      installMode: 'required',
    });
  }
  if (includeInitialRecords && optionalInstallSql.trim()) {
    const uninstallEntry = optionalUninstallSql.trim()
      ? REPACK_ADDON_OPTIONAL_UNINSTALL_SQL_ENTRY
      : undefined;
    addFile(REPACK_ADDON_OPTIONAL_INSTALL_SQL_ENTRY, `${optionalInstallSql.trim()}\n`);
    if (uninstallEntry) {
      addFile(uninstallEntry, `${optionalUninstallSql.trim()}\n`);
    }
    db_objects.push({
      objectType: 'seed',
      objectName: `${objectNameBase}_repack_initial_records`,
      installScript: REPACK_ADDON_OPTIONAL_INSTALL_SQL_ENTRY,
      uninstallScript: uninstallEntry,
      installMode: 'optional',
    });
  }

  if (
    apis.length === 0
    && ui_components.length === 0
    && ui_routes.length === 0
    && portals.length === 0
    && navigations.length === 0
    && workflows.length === 0
    && !db_objects?.length
    && !shouldPackPublicSiteHomePortal(packageId)
  ) {
    return null;
  }

  return {
    ...(apis.length > 0 ? { apis } : {}),
    ...(ui_components.length > 0 ? { ui_components } : {}),
    ...(ui_routes.length > 0 ? { ui_routes } : {}),
    ...(portals.length > 0 ? { portals } : {}),
    ...(navigations.length > 0 ? { navigations } : {}),
    ...(workflows.length > 0 ? { workflows } : {}),
    ...(db_objects?.length ? { db_objects } : {}),
    ...(studioModuleExtras
      ? {
          navigation_patches: [studioModuleExtras.navigationPatchCapability],
          culture_keys: [studioModuleExtras.cultureKeysCapability],
        }
      : {}),
    ...(shouldPackPublicSiteHomePortal(packageId)
      ? { home_portal: publicSiteHomePortalCapability() }
      : {}),
    files,
  };
}

export function attachWorkflowExportFilesToRepackAdditions(
  additions: PackageRepackAdditionsPayload | null,
  files: Array<{ path: string; content: string }>,
): PackageRepackAdditionsPayload | null {
  if (!additions) return null;
  if (files.length === 0) return additions;
  const seen = new Set(additions.files.map((file) => file.entryPath));
  const nextFiles = [...additions.files];
  for (const file of files) {
    const entryPath = file.path.replace(/\\/g, '/').replace(/^\.\//, '');
    if (!entryPath || seen.has(entryPath)) continue;
    seen.add(entryPath);
    nextFiles.push({ entryPath, content: file.content });
  }
  return { ...additions, files: nextFiles };
}

export function attachEdgeDataExportToRepackAdditions(
  additions: PackageRepackAdditionsPayload | null,
  exported: PackageEdgeDataExportResult,
): PackageRepackAdditionsPayload {
  const base = additions ?? { files: [] };
  const withFiles = attachWorkflowExportFilesToRepackAdditions(base, exported.files) ?? base;
  return {
    ...withFiles,
    ...(exported.capabilities.edge_models?.length ? { edge_models: exported.capabilities.edge_models } : {}),
    ...(exported.capabilities.edge_apis?.length ? { edge_apis: exported.capabilities.edge_apis } : {}),
    ...(exported.capabilities.edge_model_studio_meta?.length
      ? { edge_model_studio_meta: exported.capabilities.edge_model_studio_meta }
      : {}),
    ...(exported.capabilities.record_policies?.length
      ? { record_policies: exported.capabilities.record_policies }
      : {}),
    ...(exported.capabilities.record_policy_bindings?.length
      ? { record_policy_bindings: exported.capabilities.record_policy_bindings }
      : {}),
    ...(exported.capabilities.scope_dimensions?.length
      ? { scope_dimensions: exported.capabilities.scope_dimensions }
      : {}),
  };
}
