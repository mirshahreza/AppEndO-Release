/**
 * Sync BCP-47 locale options from Unicode CLDR availableLocales.
 * Source: https://github.com/unicode-org/cldr-json (cldr-core/availableLocales.json)
 *
 * Usage: npm run codegen:cldr-locales
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CLDR_AVAILABLE_LOCALES_URL = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/availableLocales.json';
const CLDR_LIKELY_SUBTAGS_URL = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/likelySubtags.json';
const PLATFORM_DEFAULT_LOCALES = ['en-US', 'fa-IR', 'ar-IQ'] as const;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/shared/lib/cldrLocaleOptions.generated.ts');

type LocaleOption = { value: string; label: string };

type CldrAvailableLocalesResponse = {
  availableLocales?: {
    full?: string[];
    modern?: string[];
  };
};

function formatLocaleLabel(tag: string): string {
  try {
    const displayName = new Intl.DisplayNames('en', { type: 'language' }).of(tag);
    if (displayName && displayName !== tag) {
      return `${displayName} (${tag})`;
    }
  } catch {
    // Fall back to the raw tag below.
  }

  return tag;
}

type CldrLikelySubtagsResponse = {
  likelySubtags?: Record<string, string>;
};

function expandLocaleVariants(tag: string): string[] {
  const variants = new Set<string>([tag]);

  try {
    const locale = new Intl.Locale(tag);
    variants.add(locale.toString());
    variants.add(locale.baseName);

    if (locale.language && locale.region) {
      variants.add(`${locale.language}-${locale.region}`);
    }
  } catch {
    // Keep the original tag only.
  }

  return [...variants];
}

function buildLocaleOptions(locales: string[]): LocaleOption[] {
  const unique = [...new Set(
    locales
      .flatMap((locale) => expandLocaleVariants(locale.trim()))
      .filter((locale) => locale && locale !== 'und'),
  )];

  unique.sort((left, right) => left.localeCompare(right));

  return unique.map((value) => ({
    value,
    label: formatLocaleLabel(value),
  }));
}

async function loadCldrLocales(): Promise<string[]> {
  const [availableResponse, likelyResponse] = await Promise.all([
    fetch(CLDR_AVAILABLE_LOCALES_URL),
    fetch(CLDR_LIKELY_SUBTAGS_URL),
  ]);

  if (!availableResponse.ok) {
    throw new Error(`Failed to fetch ${CLDR_AVAILABLE_LOCALES_URL}: ${availableResponse.status} ${availableResponse.statusText}`);
  }

  if (!likelyResponse.ok) {
    throw new Error(`Failed to fetch ${CLDR_LIKELY_SUBTAGS_URL}: ${likelyResponse.status} ${likelyResponse.statusText}`);
  }

  const availablePayload = await availableResponse.json() as CldrAvailableLocalesResponse;
  const likelyPayload = await likelyResponse.json() as CldrLikelySubtagsResponse;
  const full = availablePayload.availableLocales?.full ?? [];
  const likelySubtags = likelyPayload.likelySubtags ?? {};

  if (full.length === 0) {
    throw new Error('CLDR availableLocales.full is empty.');
  }

  return [
    ...full,
    ...Object.keys(likelySubtags),
    ...Object.values(likelySubtags),
    ...PLATFORM_DEFAULT_LOCALES,
  ];
}

function writeGeneratedFile(options: LocaleOption[]): void {
  const serialized = options
    .map((option) => `  { value: ${JSON.stringify(option.value)}, label: ${JSON.stringify(option.label)} },`)
    .join('\n');

  const contents = `/* eslint-disable */\n/** Generated by \`npm run codegen:cldr-locales\` — do not edit. */\n/** Sources: ${CLDR_AVAILABLE_LOCALES_URL} + ${CLDR_LIKELY_SUBTAGS_URL} */\n\nexport type CldrLocaleOption = { value: string; label: string };\n\nexport const CLDR_AVAILABLE_LOCALE_OPTIONS: CldrLocaleOption[] = [\n${serialized}\n];\n`;

  fs.writeFileSync(outputPath, contents, 'utf8');
}

async function main(): Promise<void> {
  const locales = await loadCldrLocales();
  const options = buildLocaleOptions(locales);
  writeGeneratedFile(options);
  console.log(`[codegen:cldr-locales] wrote ${options.length} locales to ${path.relative(root, outputPath)}`);
}

main().catch((error) => {
  console.error('[codegen:cldr-locales] failed:', error);
  process.exit(1);
});
